const LEGAL = "This product provides compliance tooling, not legal advice.";

function esc(v: unknown): string {
  return String(v ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function tierColour(tier: string): string {
  return (
    {
      PROHIBITED: "#b91c1c",
      HIGH: "#c2410c",
      LIMITED: "#a16207",
      MINIMAL: "#15803d",
    } as Record<string, string>
  )[tier] ?? "#334155";
}

